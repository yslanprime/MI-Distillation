#!/usr/bin/env python3
"""Build fixed-lambda training sets from the candidate pool.

Filters each lambda independently by answer correctness and token length,
yielding one dataset per point on the spectrum (lambda=1.0 is Short CoT,
lambda=0.0 is Long CoT).

Optional: MI-Distillation does not need this step, since
src/seqlss_selection.py applies the same filters across all lambdas at once.
"""

import argparse
import copy
import json
import random
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

from tqdm import tqdm
from transformers import AutoTokenizer


EVAL_INSTRUCTION = "Please reason step by step, and put your final answer within \\boxed{}."

PROJECT_ROOT = Path(__file__).resolve().parent.parent
EVALUATION_ROOT = PROJECT_ROOT / "evaluation"
if str(EVALUATION_ROOT) not in sys.path:
    sys.path.insert(0, str(EVALUATION_ROOT))

from data_processing.answer_extraction import extract_math_answer, strip_string  # noqa: E402
from eval.eval_script import eval_math  # noqa: E402


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Filter data/cot_generated by shared correctness.")
    parser.add_argument(
        "--input_dir",
        type=str,
        required=True,
        help="Directory containing the per-lambda CoT JSON files.",
    )
    parser.add_argument(
        "--input_glob",
        type=str,
        default="*.json",
        help="Glob pattern used recursively under input_dir.",
    )
    parser.add_argument(
        "--model_path",
        type=str,
        required=True,
        help="Student tokenizer used to count token length.",
    )
    parser.add_argument(
        "--output_dir",
        type=str,
        default="data/filter_data",
        help="Output directory.",
    )
    parser.add_argument("--train_size", type=int, default=7500, help="Train split size.")
    parser.add_argument("--val_size", type=int, default=500, help="Validation split size.")
    parser.add_argument("--seed", type=int, default=42, help="Random seed.")
    parser.add_argument("--max_length", type=int, default=8192, help="Keep token_length < max_length.")
    parser.add_argument(
        "--instruction",
        type=str,
        default=EVAL_INSTRUCTION,
        help="Instruction appended to question before tokenization.",
    )
    return parser.parse_args()


def discover_input_files(input_dir: Path, pattern: str) -> List[Path]:
    return sorted([p for p in input_dir.rglob(pattern) if p.is_file()])


def load_json_list(path: Path) -> List[Dict[str, Any]]:
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, list):
        raise ValueError(f"{path} must be a JSON list.")
    return data


def build_uid_map(records: List[Dict[str, Any]], source_path: Path) -> Dict[Any, Dict[str, Any]]:
    uid_map: Dict[Any, Dict[str, Any]] = {}
    skipped_missing_uid = 0
    skipped_empty = 0

    for idx, record in enumerate(records):
        if not isinstance(record, dict):
            skipped_empty += 1
            continue

        uid = record.get("unique_id")
        if uid is None:
            skipped_missing_uid += 1
            continue

        problem = str(record.get("problem", "")).strip()
        cot_response = str(record.get("cot_response", "")).strip()
        answer = str(record.get("answer", "")).strip()

        if not problem or not cot_response or not answer:
            skipped_empty += 1
            continue

        if uid in uid_map:
            raise ValueError(f"Duplicated unique_id={uid} in {source_path} (index={idx}).")

        normalized = copy.deepcopy(record)
        normalized["problem"] = problem
        normalized["cot_response"] = cot_response
        normalized["answer"] = answer
        uid_map[uid] = normalized

    print(
        f"Loaded {source_path}: valid={len(uid_map)}, "
        f"skipped_missing_uid={skipped_missing_uid}, skipped_empty={skipped_empty}"
    )
    return uid_map


def build_user_content(problem: str, instruction: str) -> str:
    problem = problem.strip()
    return f"{problem}\n{instruction}" if instruction else problem


def count_tokenized_length(tokenized: Any) -> int:
    if hasattr(tokenized, "get"):
        input_ids = tokenized.get("input_ids")
    elif isinstance(tokenized, dict):
        input_ids = tokenized.get("input_ids")
    else:
        input_ids = tokenized

    if input_ids is None:
        raise ValueError("Cannot find input_ids in tokenized result.")

    if isinstance(input_ids, list) and input_ids and isinstance(input_ids[0], list):
        return len(input_ids[0])
    return len(input_ids)


def compute_token_length(tokenizer, problem: str, cot_response: str, instruction: str) -> int:
    user_content = build_user_content(problem, instruction)
    assistant_content = cot_response.strip()

    if tokenizer.chat_template:
        messages = [{"role": "user", "content": user_content}]
        prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        text = f"{prompt}{assistant_content}{tokenizer.eos_token}"
        return count_tokenized_length(tokenizer(text, add_special_tokens=False))

    raise ValueError("Tokenizer has no chat_template.")


def is_correct_sample(problem: str, cot_response: str, answer: str) -> bool:
    prediction = extract_math_answer(problem, cot_response, task="math")
    ground_truth = [strip_string(answer)]
    eval_item = {"prediction": prediction, "answer": ground_truth}
    return bool(eval_math(eval_item, pred_key="prediction"))


def split_ids(shared_ids: List[Any], train_size: int, val_size: int, seed: int) -> Tuple[List[Any], List[Any]]:
    total_needed = train_size + val_size
    if len(shared_ids) < total_needed:
        raise ValueError(f"Not enough samples after filtering: need {total_needed}, got {len(shared_ids)}.")

    rng = random.Random(seed)
    shuffled = list(shared_ids)
    rng.shuffle(shuffled)
    selected = shuffled[:total_needed]
    return selected[:train_size], selected[train_size:train_size + val_size]


def make_safe_stem(input_dir: Path, input_file: Path) -> str:
    rel = input_file.relative_to(input_dir).with_suffix("")
    return str(rel).replace("/", "__")


def save_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def main() -> None:
    args = parse_args()
    input_dir = Path(args.input_dir)
    output_dir = Path(args.output_dir)

    input_files = discover_input_files(input_dir, args.input_glob)
    if not input_files:
        raise ValueError(f"No input files found under {input_dir} with pattern {args.input_glob}.")

    print("=" * 60)
    print("Per-File Correct Filter (data/cot_generated)")
    print("=" * 60)
    print(f"Input dir     : {input_dir}")
    print(f"Input glob    : {args.input_glob}")
    print(f"Files         : {len(input_files)}")
    print(f"Tokenizer     : {args.model_path}")
    print(f"Max length    : < {args.max_length}")
    print(f"Train/Val     : {args.train_size}/{args.val_size}")
    print(f"Seed          : {args.seed}")
    print(f"Output dir    : {output_dir}")
    print("=" * 60)

    print(f"Loading tokenizer from: {args.model_path}")
    tokenizer = AutoTokenizer.from_pretrained(args.model_path, trust_remote_code=True)

    for file_path in input_files:
        print(f"\n{'=' * 60}")
        print(f"Processing: {file_path}")

        records = load_json_list(file_path)
        uid_map = build_uid_map(records, file_path)
        all_ids = sorted(uid_map.keys())

        # Correctness filtering
        correct_ids: List[Any] = []
        for uid in tqdm(all_ids, desc=f"Correctness filtering [{file_path.name}]"):
            item = uid_map[uid]
            if is_correct_sample(item["problem"], item["cot_response"], item["answer"]):
                correct_ids.append(uid)
        print(f"Correct ids: {len(correct_ids)} / {len(all_ids)}")

        # Token length filtering
        final_ids: List[Any] = []
        skipped_too_long = 0
        for uid in tqdm(correct_ids, desc=f"Token length filtering [{file_path.name}]"):
            item = uid_map[uid]
            token_length = compute_token_length(
                tokenizer=tokenizer,
                problem=item["problem"],
                cot_response=item["cot_response"],
                instruction=args.instruction,
            )
            item["token_length"] = token_length
            if token_length >= args.max_length:
                skipped_too_long += 1
                continue
            final_ids.append(uid)
        print(f"Skipped too-long ids: {skipped_too_long}")
        print(f"Final ids after all filtering: {len(final_ids)}")

        train_ids, val_ids = split_ids(final_ids, args.train_size, args.val_size, args.seed)
        print(f"Train ids: {len(train_ids)}")
        print(f"Val ids  : {len(val_ids)}")

        safe_stem = make_safe_stem(input_dir, file_path)
        train_data = [copy.deepcopy(uid_map[uid]) for uid in train_ids]
        val_data = [copy.deepcopy(uid_map[uid]) for uid in val_ids]

        train_file = output_dir / f"{safe_stem}_all_correct_train{args.train_size}.json"
        val_file = output_dir / f"{safe_stem}_all_correct_val{args.val_size}.json"
        save_json(train_file, train_data)
        save_json(val_file, val_data)

        print(f"  Train: {train_file} ({len(train_data)})")
        print(f"  Val  : {val_file} ({len(val_data)})")

    print("=" * 60)
    print("Done.")
    print("=" * 60)


if __name__ == "__main__":
    main()
